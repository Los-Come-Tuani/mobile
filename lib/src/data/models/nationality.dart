/// Un país de nacionalidad: el código ISO 3166-1 de dos letras que pide la API y su nombre.
class Nationality {
  const Nationality(this.code, this.name);

  final String code;
  final String name;

  /// El país de la gente que usa K'Plan: va primero en el selector.
  static const home = 'NI';

  /// `null` si [code] no está en la lista.
  static Nationality? byCode(String? code) {
    if (code == null) return null;
    final upper = code.toUpperCase();
    for (final item in all) {
      if (item.code == upper) return item;
    }
    return null;
  }

  static const List<Nationality> all = _countries;
}

